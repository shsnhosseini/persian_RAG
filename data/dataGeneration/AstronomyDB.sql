/* ------------------------------------------------------------
   1) جدول ستارگان
   ------------------------------------------------------------ */
CREATE TABLE dbo.Stars
(
    StarID                INT IDENTITY(1,1) NOT NULL
        CONSTRAINT PK_Stars PRIMARY KEY,
    PersianName           NVARCHAR(100) NOT NULL,   -- نام فارسی
    EnglishName           NVARCHAR(100) NOT NULL,   -- نام لاتین
    Constellation         NVARCHAR(100) NULL,       -- صورت فلکی
    SpectralType          NVARCHAR(20)  NULL,       -- رده طیفی
    DistanceLightYears    DECIMAL(18,4) NULL,       -- فاصله (سال نوری)
    MassSolar             DECIMAL(18,6) NULL,       -- جرم (نسبت به خورشید)
    RadiusSolar           DECIMAL(18,6) NULL,       -- شعاع (نسبت به خورشید)
    SurfaceTempK          INT           NULL,       -- دمای سطح (کلوین)
    LuminositySolar       DECIMAL(18,6) NULL,       -- درخشندگی (نسبت به خورشید)
    AgeMillionYears       DECIMAL(18,2) NULL,       -- سن (میلیون سال)
    ApparentMagnitude     DECIMAL(6,2)  NULL,       -- قدر ظاهری
    AbsoluteMagnitude     DECIMAL(6,2)  NULL,       -- قدر مطلق
    Color                 NVARCHAR(50)  NULL,       -- رنگ
    NumberOfKnownPlanets  INT NOT NULL
        CONSTRAINT DF_Stars_PlanetCount DEFAULT(0), -- تعداد سیارات شناخته‌شده
    DiscoveryYear         INT           NULL,       -- سال کشف/ثبت
    Description           NVARCHAR(1000) NULL       -- توضیح فارسی
);
GO

/* ------------------------------------------------------------
   2) جدول سیارات
   ------------------------------------------------------------ */
CREATE TABLE dbo.Planets
(
    PlanetID              INT IDENTITY(1,1) NOT NULL
        CONSTRAINT PK_Planets PRIMARY KEY,
    PersianName           NVARCHAR(100) NOT NULL,   -- نام فارسی
    EnglishName           NVARCHAR(100) NOT NULL,   -- نام لاتین
    StarID                INT NOT NULL,             -- ستاره میزبان
    PlanetType            NVARCHAR(50)  NULL,       -- نوع سیاره
    DistanceFromStarAU    DECIMAL(18,6) NULL,       -- فاصله از ستاره (واحد نجومی)
    OrbitalPeriodDays     DECIMAL(18,4) NULL,       -- دوره مداری (روز)
    MassEarth             DECIMAL(18,6) NULL,       -- جرم (نسبت به زمین)
    RadiusEarth           DECIMAL(18,6) NULL,       -- شعاع (نسبت به زمین)
    SurfaceGravity        DECIMAL(10,4) NULL,       -- گرانش سطحی (m/s²)
    MeanTempC             DECIMAL(10,2) NULL,       -- میانگین دما (سلسیوس)
    AtmosphereMain        NVARCHAR(200) NULL,       -- ترکیب اصلی جو
    NumberOfMoons         INT           NULL,       -- تعداد قمر
    DiscoveryYear         INT           NULL,       -- سال کشف
    DiscoveryMethod       NVARCHAR(100) NULL,       -- روش کشف
    InHabitableZone       BIT NOT NULL
        CONSTRAINT DF_Planets_HZ DEFAULT(0),        -- در کمربند حیات؟
    Description           NVARCHAR(1000) NULL,      -- توضیح فارسی
    CONSTRAINT FK_Planets_Stars
        FOREIGN KEY (StarID) REFERENCES dbo.Stars(StarID)
);
GO

