# ---------------------------------------------------------------- استایل‌ها
HEADER_FILL = PatternFill("solid", start_color="1F4E78", end_color="1F4E78")
HEADER_FONT = Font(name="Tahoma", size=11, bold=True, color="FFFFFF")
BODY_FONT   = Font(name="Tahoma", size=10)
ALT_FILL    = PatternFill("solid", start_color="EAF1F8", end_color="EAF1F8")
THIN = Side(style="thin", color="B7C6D9")
BORDER = Border(left=THIN, right=THIN, top=THIN, bottom=THIN)


def build_sheet(ws, headers, rows, widths, num_cols=()):
    ws.sheet_view.rightToLeft = True

    ws.append(headers)
    for c in range(1, len(headers) + 1):
        cell = ws.cell(row=1, column=c)
        cell.fill = HEADER_FILL
        cell.font = HEADER_FONT
        cell.alignment = Alignment(horizontal="center", vertical="center", wrap_text=True)
        cell.border = BORDER
    ws.row_dimensions[1].height = 34

    for r_i, row in enumerate(rows, start=2):
        ws.append(row)
        for c in range(1, len(headers) + 1):
            cell = ws.cell(row=r_i, column=c)
            cell.font = BODY_FONT
            cell.border = BORDER
            is_num = c in num_cols and isinstance(cell.value, (int, float))
            cell.alignment = Alignment(
                horizontal="center" if is_num else "right",
                vertical="center",
                wrap_text=not is_num,
            )
            if r_i % 2 == 0:
                cell.fill = ALT_FILL

    for i, w in enumerate(widths, start=1):
        ws.column_dimensions[get_column_letter(i)].width = w

    ws.freeze_panes = "A2"
    ws.auto_filter.ref = f"A1:{get_column_letter(len(headers))}{len(rows) + 1}"


def main():
    wb = openpyxl.Workbook()

    ws1 = wb.active
    ws1.title = SHEET1_NAME
    build_sheet(
        ws1, SHEET1_HEADERS, SHEET1_ROWS,
        widths=[8, 22, 22, 9, 11, 20, 28, 28, 48, 28, 38, 58, 10],
        num_cols=(1, 4, 5),
    )

    ws2 = wb.create_sheet(SHEET2_NAME)
    build_sheet(
        ws2, SHEET2_HEADERS, SHEET2_ROWS,
        widths=[8, 26, 32, 8, 24, 58, 36, 12, 26],
        num_cols=(1, 4),
    )

    wb.properties.title = "دانشمندان علوم کامپیوتر — داده آزمایشی RAG فارسی"
    wb.properties.creator = "Persian RAG Test Dataset"
    wb.properties.subject = "Computer Scientists (Farsi)"

    filename = "computer_scientists_fa.xlsx"
    wb.save(filename)
    print(f"✅ فایل ساخته شد: {filename}")
    print(f"   شیت ۱: {SHEET1_NAME} — {len(SHEET1_ROWS)} ردیف × {len(SHEET1_HEADERS)} ستون")
    print(f"   شیت ۲: {SHEET2_NAME} — {len(SHEET2_ROWS)} ردیف × {len(SHEET2_HEADERS)} ستون")


